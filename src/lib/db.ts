function getDatabaseUrl() {
  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) {
    throw new Error('DATABASE_URL is required. Set it to your Neon pooled PostgreSQL connection string.');
  }
  return databaseUrl;
}

export function getPool() {
  if (!globalForPg.collabDictionaryPool) {
    globalForPg.collabDictionaryPool = new Pool({
      connectionString: getDatabaseUrl(),
      max: 5,
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 10_000,
      ssl: { rejectUnauthorized: false },
    });
  }
  return globalForPg.collabDictionaryPool;
}

