export async function getWordMatchRound(input: {
  excludedLanguages?: string[];
  preferredLanguage: 'english' | 'french';
  excludeId?: number | null;
  previousLanguage?: string | null;
}) {
  await ensureSchema();

  const excludedLanguages = [...new Set(input.excludedLanguages ?? [])].filter(Boolean);
  const pool = getPool();
  const answerLanguage = input.preferredLanguage;

  const answerColumn = 'french';
  const answerFilter = `AND trim(w.french) <> ''`;

  const wordResult = await pool.query<{
    id: number;
    french: string;
    english: string;
    contribution_clues: GameTranslationClue[] | null;
  }>(
    `
    WITH latest_contributions AS (
      SELECT DISTINCT ON (word_id, language)
        word_id,
        language,
        translation
      FROM contributions
      WHERE status <> 'rejected'
        AND trim(translation) <> ''
        AND NOT (language = ANY($1::text[]))
        AND language = ANY($4::text[])
      ORDER BY word_id, language, created_at DESC, id DESC
    ),
    candidate_clues AS (
      SELECT
        w.id AS word_id,
        'nufi'::text AS language,
        nufi_value.translation
      FROM predefined_words w
      CROSS JOIN LATERAL jsonb_array_elements_text(w.nufi_json) AS nufi_value(translation)
      WHERE 'nufi' <> ALL($1::text[])
        AND trim(nufi_value.translation) <> ''
        AND trim(w.${answerColumn}) <> ''
        ${answerFilter}

      UNION ALL

      SELECT
        w.id AS word_id,
        lc.language,
        lc.translation
      FROM predefined_words w
      INNER JOIN latest_contributions lc ON lc.word_id = w.id
      WHERE trim(w.${answerColumn}) <> ''
        ${answerFilter}
    ),
    available_languages AS (
      SELECT DISTINCT language
      FROM candidate_clues
    ),
    selected_language AS (
      SELECT language
      FROM available_languages
      WHERE (
        $3::text IS NULL
        OR language <> $3
        OR (SELECT COUNT(*) FROM available_languages) = 1
      )
      ORDER BY random()
      LIMIT 1
    ),
    selected_word AS (
      SELECT
        w.id,
        w.french,
        w.english
      FROM candidate_clues clue
      INNER JOIN selected_language selected ON selected.language = clue.language
      INNER JOIN predefined_words w ON w.id = clue.word_id
      WHERE ($2::int IS NULL OR w.id <> $2)
      ORDER BY random()
      LIMIT 1
    )
    SELECT
      selected_word.id,
      selected_word.french,
      selected_word.english,
      COALESCE(
        jsonb_agg(
          jsonb_build_object('language', clue.language, 'translation', clue.translation)
          ORDER BY
            CASE WHEN clue.language = selected_language.language THEN 0 ELSE 1 END,
            random()
        ) FILTER (WHERE clue.translation IS NOT NULL),
        '[]'::jsonb
      ) AS contribution_clues
    FROM selected_word
    CROSS JOIN selected_language
    INNER JOIN candidate_clues clue ON clue.word_id = selected_word.id
    GROUP BY selected_word.id, selected_word.french, selected_word.english
  `,
    [
      excludedLanguages,
      input.excludeId ?? null,
      input.previousLanguage ?? null,
      LANGUAGES.filter((language) => language.id !== 'other').map((language) => language.id),
    ]
  );

  const word = wordResult.rows[0];
  if (!word) return null;

  const clues: GameTranslationClue[] = [];
  for (const clue of word.contribution_clues ?? []) {
    const translation = String(clue.translation ?? '').trim();
    if (translation) clues.push({ language: clue.language, translation });
  }

  const choicesResult = await pool.query<{ answer: string }>(
    `
    SELECT answer
    FROM (
      SELECT DISTINCT w.${answerColumn} AS answer
      FROM predefined_words w
      WHERE trim(w.${answerColumn}) <> ''
        ${answerFilter}
        AND w.id <> $1
    ) answers
    ORDER BY random()
    LIMIT 120
  `,
    [word.id]
  );

  const correctSourceAnswer = word.french;
  const correctAnswer = answerLanguage === 'english' ? await translateFrenchToEnglish(correctSourceAnswer) : correctSourceAnswer;
  const correctAnswerIsNumber = isNumberLikeAnswer(correctSourceAnswer);
  const choices = [correctAnswer];
  for (const row of choicesResult.rows) {
    const sourceAnswer = normalizeAnswer(row.answer);
    const answer = answerLanguage === 'english' ? await translateFrenchToEnglish(sourceAnswer) : sourceAnswer;
    if (
      answer &&
      isNumberLikeAnswer(sourceAnswer) === correctAnswerIsNumber &&
      !choices.some((choice) => choice.toLocaleLowerCase() === answer.toLocaleLowerCase())
    ) {
      choices.push(answer);
    }
    if (choices.length >= 4) break;
  }

  return {
    id: word.id,
    french: word.french,
    english: word.english,
    clues,
    correctAnswer,
    choices,
    answerLanguage,
  };
}

export async function listPlayableGameLanguages() {
  await ensureSchema();

  const publicLanguageIds = LANGUAGES.filter((language) => language.id !== 'other').map((language) => language.id);
  const result = await getPool().query<{ language: string; word_count: number }>(
    `
    WITH nufi_words AS (
      SELECT DISTINCT 'nufi'::text AS language, w.id AS word_id
      FROM predefined_words w
      WHERE jsonb_array_length(w.nufi_json) > 0
        AND trim(w.french) <> ''
    ),
    contribution_words AS (
      SELECT DISTINCT c.language, c.word_id
      FROM contributions c
      INNER JOIN predefined_words w ON w.id = c.word_id
      WHERE c.status <> 'rejected'
        AND trim(c.translation) <> ''
        AND trim(w.french) <> ''
        AND c.language = ANY($1::text[])
    )
    SELECT language, COUNT(DISTINCT word_id)::int AS word_count
    FROM (
      SELECT * FROM nufi_words
      UNION ALL
      SELECT * FROM contribution_words
    ) playable
    GROUP BY language
    ORDER BY language ASC
  `,
    [publicLanguageIds]
  );

  return result.rows;
}

export async function listComparisonWords(input: { q?: string; offset?: number; limit?: number }) {
  await ensureSchema();
  const limit = normalizeLimit(input.limit, 20);
  const offset = normalizeOffset(input.offset);
  const q = input.q?.trim().toLocaleLowerCase() ?? '';
  const where = q
    ? `AND (
        w.search_text ILIKE $1
        OR EXISTS (
          SELECT 1
          FROM contributions search_c
          WHERE search_c.word_id = w.id
            AND search_c.status <> 'rejected'
            AND (
              search_c.language ILIKE $1
              OR search_c.translation ILIKE $1
              OR search_c.synonyms ILIKE $1
              OR search_c.contributor_name ILIKE $1
            )
        )
      )`
    : '';
  const searchParams = q ? [`%${q}%`] : [];

  const pool = getPool();
  const countResult = await pool.query<{ total: string }>(
    `
    SELECT COUNT(*) AS total
    FROM predefined_words w
    WHERE EXISTS (
      SELECT 1
      FROM contributions c
      WHERE c.word_id = w.id AND c.status <> 'rejected'
    )
    ${where}
  `,
    searchParams
  );

  const rowsResult = await pool.query<ComparisonWordRow>(
    `
    SELECT
      w.id,
      w.french,
      w.english,
      w.nufi_json,
      COUNT(c.id)::int AS contribution_count,
      COUNT(DISTINCT c.language)::int AS language_count
    FROM predefined_words w
    INNER JOIN contributions c ON c.word_id = w.id AND c.status <> 'rejected'
    WHERE 1 = 1
      ${where}
    GROUP BY w.id
    ORDER BY language_count DESC, contribution_count DESC, w.id ASC
    LIMIT $${searchParams.length + 1} OFFSET $${searchParams.length + 2}
  `,
    [...searchParams, limit, offset]
  );

  const wordIds = rowsResult.rows.map((row) => row.id);
  const contributionRows =
    wordIds.length > 0
      ? (
          await pool.query<WordComparisonContribution>(
            `
            SELECT id, word_id, language, translation, synonyms, contributor_name, contributor_email, notes, status, created_at
            FROM contributions
            WHERE word_id = ANY($1::int[])
              AND status <> 'rejected'
            ORDER BY word_id ASC, language ASC, created_at DESC, id DESC
          `,
            [wordIds]
          )
        ).rows
      : [];

  const contributionsByWordId = new Map<number, WordComparisonContribution[]>();
  for (const contribution of contributionRows) {
    const current = contributionsByWordId.get(contribution.word_id) ?? [];
    current.push(contribution);
    contributionsByWordId.set(contribution.word_id, current);
  }

  return {
    rows: rowsResult.rows,
    total: Number(countResult.rows[0]?.total ?? 0),
    limit,
    offset,
    contributionsByWordId,
  };
}

