export async function listAdminWords(input: { language: string; q?: string; offset?: number; limit?: number }) {
  await ensureSchema();
  const limit = normalizeLimit(input.limit, 50);
  const offset = normalizeOffset(input.offset);
  const language = input.language.trim();
  const q = input.q?.trim() ?? '';
  const searchPattern = q ? `%${q}%` : null;
  const searchWhere = searchPattern
    ? `AND (
        w.search_text ILIKE $2
        OR c.translation ILIKE $2
        OR c.synonyms ILIKE $2
        OR c.contributor_name ILIKE $2
        OR c.contributor_email ILIKE $2
      )`
    : '';
  const params = searchPattern ? [language, searchPattern, limit, offset] : [language, limit, offset];
  const limitParam = searchPattern ? '$3' : '$2';
  const offsetParam = searchPattern ? '$4' : '$3';

  const countResult = await getPool().query<{ total: string }>(
    `
    SELECT COUNT(*) AS total
    FROM predefined_words w
    LEFT JOIN LATERAL (
      SELECT translation, synonyms, contributor_name, contributor_email
      FROM contributions
      WHERE word_id = w.id AND language = $1
      ORDER BY created_at DESC, id DESC
      LIMIT 1
    ) c ON true
    WHERE 1 = 1
      ${searchWhere}
  `,
    searchPattern ? [language, searchPattern] : [language]
  );

  const rowsResult = await getPool().query<AdminWordRow>(
    `
    SELECT
      w.id AS word_id,
      w.french,
      w.english,
      w.nufi_json,
      c.id AS contribution_id,
      c.language,
      c.translation,
      c.synonyms,
      c.contributor_name,
      c.contributor_email,
      c.notes,
      c.status,
      c.created_at
    FROM predefined_words w
    LEFT JOIN LATERAL (
      SELECT id, language, translation, synonyms, contributor_name, contributor_email, notes, status, created_at
      FROM contributions
      WHERE word_id = w.id AND language = $1
      ORDER BY created_at DESC, id DESC
      LIMIT 1
    ) c ON true
    WHERE 1 = 1
      ${searchWhere}
    ORDER BY
      CASE WHEN c.id IS NULL THEN 1 ELSE 0 END,
      w.source_row ASC,
      w.id ASC
    LIMIT ${limitParam} OFFSET ${offsetParam}
  `,
    params
  );

  return { rows: rowsResult.rows, total: Number(countResult.rows[0]?.total ?? 0), limit, offset };
}

export async function upsertAdminWordContribution(input: {
  wordId: number;
  contributionId?: number | null;
  language: string;
  translation: string;
  synonyms: string;
  contributorName: string;
  notes: string;
  status: string;
}) {
  await ensureSchema();
  if (input.contributionId) {
    const result = await updateAdminContribution({
      id: input.contributionId,
      language: input.language,
      translation: input.translation,
      synonyms: input.synonyms,
      contributorName: input.contributorName,
      notes: input.notes,
      status: input.status,
    });
    return result?.id ?? null;
  }

  const result = await getPool().query<{ id: number }>(
    `
    INSERT INTO contributions (word_id, language, translation, synonyms, contributor_name, notes, status)
    VALUES ($1, $2, $3, $4, $5, $6, $7)
    RETURNING id
  `,
    [
      input.wordId,
      input.language.trim(),
      input.translation.trim(),
      input.synonyms.trim(),
      input.contributorName.trim(),
      input.notes.trim(),
      input.status.trim(),
    ]
  );
  return result.rows[0]?.id ?? null;
}

export async function updateAdminContribution(input: {
  id: number;
  language: string;
  translation: string;
  synonyms: string;
  contributorName: string;
  notes: string;
  status: string;
}) {
  await ensureSchema();
  if (input.status.trim() === 'rejected') {
    const target = await getPool().query<{
      id: number;
      word_id: number;
      language: string;
      translation: string;
      synonyms: string;
    }>(
      `
      SELECT id, word_id, language, translation, synonyms
      FROM contributions
      WHERE id = $1
      LIMIT 1
    `,
      [input.id]
    );

    const row = target.rows[0];
    if (!row) return null;

    await getPool().query(
      `
      UPDATE contributions
      SET status = 'rejected'
      WHERE word_id = $1
        AND language = $2
        AND translation = $3
        AND synonyms = $4
    `,
      [row.word_id, row.language, row.translation, row.synonyms]
    );

    return { id: row.id };
  }

  const result = await getPool().query<{ id: number }>(
    `
    UPDATE contributions
    SET language = $2,
        translation = $3,
        synonyms = $4,
        contributor_name = $5,
        notes = $6,
        status = $7
    WHERE id = $1
    RETURNING id
  `,
    [
      input.id,
      input.language.trim(),
      input.translation.trim(),
      input.synonyms.trim(),
      input.contributorName.trim(),
      input.notes.trim(),
      input.status.trim(),
    ]
  );
  return result.rows[0] ?? null;
}

export async function deleteAdminContribution(id: number) {
  await ensureSchema();
  const target = await getPool().query<{
    word_id: number;
    language: string;
    translation: string;
    synonyms: string;
  }>(
    `
    SELECT word_id, language, translation, synonyms
    FROM contributions
    WHERE id = $1
    LIMIT 1
  `,
    [id]
  );

  const row = target.rows[0];
  if (!row) return false;

  const result = await getPool().query(
    `
    DELETE FROM contributions
    WHERE word_id = $1
      AND language = $2
      AND translation = $3
      AND synonyms = $4
  `,
    [row.word_id, row.language, row.translation, row.synonyms]
  );
  return (result.rowCount ?? 0) > 0;
}

export async function getAdminPasswordHash(email: string) {
  await ensureSchema();
  const result = await getPool().query<{ password_hash: string }>(
    `SELECT password_hash FROM admin_users WHERE email = $1 LIMIT 1`,
    [email.trim().toLowerCase()]
  );
  return result.rows[0]?.password_hash ?? null;
}

export async function setAdminPasswordHash(email: string, passwordHash: string) {
  await ensureSchema();
  await getPool().query(
    `
    INSERT INTO admin_users (email, password_hash)
    VALUES ($1, $2)
    ON CONFLICT (email)
    DO UPDATE SET password_hash = EXCLUDED.password_hash,
                  password_updated_at = now()
  `,
    [email.trim().toLowerCase(), passwordHash]
  );
}
