function normalizeLimit(value: number | undefined, fallback: number) {
  return Math.max(1, Math.min(80, value ?? fallback));
}

function normalizeOffset(value: number | undefined) {
  return Math.max(0, value ?? 0);
}

function isNumberLikeAnswer(value: string) {
  return /^[+-]?\d+(?:[.,]\d+)?$/.test(value.trim());
}

function normalizeAnswer(value: string) {
  return value.replace(/\s+/g, ' ').trim();
}

async function translateFrenchToEnglish(sourceText: string) {
  const normalizedSource = normalizeAnswer(sourceText);
  if (!normalizedSource || isNumberLikeAnswer(normalizedSource)) return normalizedSource;

  const pool = getPool();
  const cached = await pool.query<{ translated_text: string }>(
    `
    SELECT translated_text
    FROM translation_cache
    WHERE source_language = 'fr'
      AND target_language = 'en'
      AND source_text = $1
    LIMIT 1
    `,
    [normalizedSource]
  );

  const cachedText = normalizeAnswer(cached.rows[0]?.translated_text ?? '');
  if (cachedText) return cachedText;

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 6000);
  let translatedText = '';
  try {
    const url = new URL('https://api.mymemory.translated.net/get');
    url.searchParams.set('q', normalizedSource);
    url.searchParams.set('langpair', 'fr|en');
    const response = await fetch(url, { signal: controller.signal, cache: 'no-store' });
    const payload = (await response.json().catch(() => null)) as { responseData?: { translatedText?: string } } | null;
    translatedText = normalizeAnswer(payload?.responseData?.translatedText ?? '');
  } catch {
    translatedText = '';
  } finally {
    clearTimeout(timeout);
  }

  const finalText = translatedText || normalizedSource;
  await pool
    .query(
      `
      INSERT INTO translation_cache (source_language, target_language, source_text, translated_text, provider, updated_at)
      VALUES ('fr', 'en', $1, $2, $3, now())
      ON CONFLICT (source_language, target_language, source_text)
      DO UPDATE SET
        translated_text = EXCLUDED.translated_text,
        provider = EXCLUDED.provider,
        updated_at = now()
      `,
      [normalizedSource, finalText, translatedText ? 'mymemory' : 'fallback']
    )
    .catch(() => undefined);

  return finalText;
}

export async function listWords(input: { language: string; q?: string; offset?: number; limit?: number }) {
  await ensureSchema();
  const limit = normalizeLimit(input.limit, 24);
  const offset = normalizeOffset(input.offset);
  const q = input.q?.trim().toLocaleLowerCase() ?? '';
  const searchPattern = q ? `%${q}%` : null;
  const params = searchPattern ? [input.language, searchPattern, limit, offset] : [input.language, limit, offset];
  const where = searchPattern ? `WHERE w.search_text ILIKE $2` : '';
  const limitParam = searchPattern ? '$3' : '$2';
  const offsetParam = searchPattern ? '$4' : '$3';
  const countWhere = q ? `WHERE w.search_text ILIKE $1` : '';

  const pool = getPool();
  const countResult = await pool.query<{ total: string }>(
    `SELECT COUNT(*) AS total FROM predefined_words w ${countWhere}`,
    searchPattern ? [searchPattern] : []
  );
  const rowsResult = await pool.query<WordRow>(
    `
    SELECT
      w.id,
      w.french,
      w.english,
      w.nufi_json,
      COALESCE(stats.contribution_count, 0)::int AS contribution_count,
      latest.translation AS latest_translation,
      latest.synonyms AS latest_synonyms
    FROM predefined_words w
    LEFT JOIN LATERAL (
      SELECT COUNT(*)::int AS contribution_count
      FROM contributions c
      WHERE c.word_id = w.id
        AND c.language = $1
        AND c.status <> 'rejected'
    ) stats ON true
    LEFT JOIN LATERAL (
      SELECT c.translation, c.synonyms
      FROM contributions c
      WHERE c.word_id = w.id
        AND c.language = $1
        AND c.status <> 'rejected'
      ORDER BY c.created_at DESC, c.id DESC
      LIMIT 1
    ) latest ON true
    ${where}
    ORDER BY
      CASE WHEN COALESCE(stats.contribution_count, 0) = 0 THEN 0 ELSE 1 END,
      w.source_row ASC,
      w.id ASC
    LIMIT ${limitParam} OFFSET ${offsetParam}
  `,
    params
  );

  return { rows: rowsResult.rows, total: Number(countResult.rows[0]?.total ?? 0), limit, offset };
}

